#!/usr/bin/env bash
# ==============================================================================
# scripts/restore_db.sh
# Fail-safe, non-destructive PostgreSQL restoration script.
# Part of H-03: Production Deployment & Data Recovery Architecture.
#
# SECURITY NOTICE:
# The SHA-256 checksum provides archive integrity against transmission errors,
# disk corruption, and truncation. It DOES NOT provide cryptographic authenticity
# or non-repudiation against an adversary with write access to storage.
# In production, off-site backups require digital signatures (e.g. GPG) or
# immutable object storage (S3 Object Lock in Compliance Mode).
# ==============================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PYTHON="${PYTHON:-$ROOT/.venv/bin/python}"
if [[ ! -x "$PYTHON" ]]; then
  PYTHON="python3"
fi

usage() {
  cat <<EOF
Usage: $(basename "$0") <DUMP_FILE> <TARGET_DB> [OPTIONS]

Arguments:
  DUMP_FILE              Path to the .dump file generated by backup_db.sh
  TARGET_DB              Name of the new, isolated target database to restore into

Options:
  --url DATABASE_URL     Base PostgreSQL connection URL (without target database name)
  -h, --help             Show this help message and exit

SAFETY ENFORCEMENT:
  - Target database MUST NOT already exist.
  - Target database CANNOT be fireassets, fireassets_test, or fireassets_concurrency_test.
  - Checksum verification is mandatory prior to creating or restoring any database.
EOF
  exit 1
}

if [[ $# -lt 2 ]]; then
  usage
fi

DUMP_FILE="$1"
TARGET_DB="$2"
shift 2

DB_URL=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --url)
      DB_URL="$2"
      shift 2
      ;;
    -h|--help)
      usage
      ;;
    *)
      echo "Unknown option: $1" >&2
      usage
      ;;
  esac
done

# 1. Validate DUMP_FILE exists
if [[ ! -f "$DUMP_FILE" ]]; then
  echo "Error: Dump file '$DUMP_FILE' not found." >&2
  exit 1
fi

# 2. Checksum verification prior to any database operation
SHA_FILE="${DUMP_FILE%.*}.sha256"
META_FILE="${DUMP_FILE%.*}.meta.json"
EXPECTED_SHA=""

if [[ -f "$SHA_FILE" ]]; then
  EXPECTED_SHA="$(cut -d' ' -f1 < "$SHA_FILE" | tr -d ' \n\r')"
elif [[ -f "$META_FILE" ]]; then
  EXPECTED_SHA="$("$PYTHON" -c "
import json, sys
try:
    with open(sys.argv[1], encoding='utf-8') as f:
        meta = json.load(f)
        print(meta.get('sha256', ''))
except Exception:
    pass
" "$META_FILE")"
fi

if [[ -z "$EXPECTED_SHA" ]]; then
  echo "Error: No checksum found for '$DUMP_FILE' (missing .sha256 or .meta.json). Cannot verify archive integrity." >&2
  exit 1
fi

compute_sha256_file() {
  local target="$1"
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$target" | awk '{print $1}'
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$target" | awk '{print $1}'
  else
    "$PYTHON" -c "
import hashlib, sys
h = hashlib.sha256()
with open(sys.argv[1], 'rb') as f:
    for chunk in iter(lambda: f.read(65536), b''):
        h.update(chunk)
print(h.hexdigest())
" "$target"
  fi
}

COMPUTED_SHA="$(compute_sha256_file "$DUMP_FILE")"

if [[ "$COMPUTED_SHA" != "$EXPECTED_SHA" ]]; then
  echo "SECURITY GUARD: Checksum verification FAILED for '$DUMP_FILE'!" >&2
  echo "  Expected: $EXPECTED_SHA" >&2
  echo "  Computed: $COMPUTED_SHA" >&2
  echo "Restoration aborted before touching any database." >&2
  exit 1
fi

echo "Checksum verified: $COMPUTED_SHA"

# 3. Security check: Validate TARGET_DB name
TARGET_DB="$(echo "$TARGET_DB" | tr -d '[:space:]')"
LOWER_TARGET="$(echo "$TARGET_DB" | tr '[:upper:]' '[:lower:]')"
case "$LOWER_TARGET" in
  fireassets|fireassets_test|fireassets_concurrency_test|postgres|template0|template1)
    echo "SECURITY GUARD: Restoration to protected database '$TARGET_DB' is strictly forbidden." >&2
    exit 1
    ;;
esac

if [[ ! "$TARGET_DB" =~ ^[a-zA-Z0-9_]+$ ]]; then
  echo "Error: Target database name '$TARGET_DB' contains invalid characters. Use only alphanumeric and underscores." >&2
  exit 1
fi

# Parse connection URL if provided, without command-line leakage or eval
DB_URL="${DB_URL:-${DATABASE_URL:-}}"
if [[ -n "$DB_URL" ]]; then
  PARSER_STATUS=""
  PARSED_HOST=""
  PARSED_PORT=""
  PARSED_USER=""
  PARSED_PASS=""
  PARSED_DB=""

  {
    IFS= read -r -d '' PARSED_HOST || true
    IFS= read -r -d '' PARSED_PORT || true
    IFS= read -r -d '' PARSED_USER || true
    IFS= read -r -d '' PARSED_PASS || true
    IFS= read -r -d '' PARSED_DB || true
    IFS= read -r -d '' PARSER_STATUS || true
  } < <(
    printf '%s' "$DB_URL" | "$PYTHON" -c '
import sys
from urllib.parse import unquote, urlsplit

try:
    raw = sys.stdin.read().rstrip("\r\n")
    if not raw:
        sys.exit(1)
    if raw.startswith("postgresql+asyncpg://"):
        raw_std = "postgresql://" + raw[len("postgresql+asyncpg://"):]
    else:
        raw_std = raw
    parsed = urlsplit(raw_std)
    if parsed.scheme != "postgresql":
        sys.stderr.write("Error: DATABASE_URL must have postgresql:// or postgresql+asyncpg:// scheme.\n")
        sys.exit(1)
    host = unquote(parsed.hostname) if parsed.hostname else ""
    port = str(parsed.port) if parsed.port else ""
    user = unquote(parsed.username) if parsed.username else ""
    pw = unquote(parsed.password) if parsed.password else ""
    db = unquote(parsed.path.lstrip("/")) if parsed.path else ""

    for field in (host, port, user, pw, db, "PARSE_SUCCESS_V1"):
        sys.stdout.buffer.write(field.encode("utf-8") + b"\0")
    sys.stdout.buffer.flush()
except Exception:
    sys.stderr.write("Error: malformed DATABASE_URL.\n")
    sys.exit(1)
'
  )

  if [[ "$PARSER_STATUS" != "PARSE_SUCCESS_V1" ]]; then
    echo "Error: Failed to parse database URL (invalid scheme or malformed URL)." >&2
    exit 1
  fi

  [[ -n "$PARSED_HOST" ]] && export PGHOST="$PARSED_HOST"
  [[ -n "$PARSED_PORT" ]] && export PGPORT="$PARSED_PORT"
  [[ -n "$PARSED_USER" ]] && export PGUSER="$PARSED_USER"
  [[ -n "$PARSED_PASS" ]] && export PGPASSWORD="$PARSED_PASS"
fi

# 4. Enforce that TARGET_DB does NOT already exist
EXISTS="$("$PYTHON" -c "
import subprocess, sys
db = sys.argv[1].replace(\"'\", \"''\")
try:
    res = subprocess.run(
        ['psql', '-d', 'postgres', '-t', '-A', '-c', f\"SELECT 1 FROM pg_database WHERE datname = '{db}';\"],
        capture_output=True, text=True, check=True
    )
    print(res.stdout.strip())
except subprocess.CalledProcessError as e:
    sys.stderr.write(f\"Error checking database existence: {e.stderr.strip()}\\n\")
    sys.exit(1)
except Exception as e:
    sys.stderr.write(f\"Error: {e}\\n\")
    sys.exit(1)
" "$TARGET_DB")"

if [[ "$EXISTS" == "1" ]]; then
  echo "SECURITY GUARD: Target database '$TARGET_DB' already exists." >&2
  echo "Restoration will NEVER overwrite an existing database. Target must be a new, isolated database." >&2
  exit 1
fi

# 5. Safe creation and isolated restore
CREATED_TARGET=0
cleanup_target_on_failure() {
  local exit_code=$?
  if [[ $exit_code -ne 0 && $CREATED_TARGET -eq 1 ]]; then
    # Defensive guard: never drop any protected database under any circumstance
    case "$LOWER_TARGET" in
      fireassets|fireassets_test|fireassets_concurrency_test|postgres|template0|template1)
        return
        ;;
    esac
    echo "Restoration encountered an error (exit code $exit_code)." >&2
    echo "Cleaning up exclusively created temporary database '$TARGET_DB'..." >&2
    psql -d postgres -c "DROP DATABASE IF EXISTS \"$TARGET_DB\";" >/dev/null 2>&1 || true
  fi
}
trap cleanup_target_on_failure EXIT

echo "Creating new target database '$TARGET_DB'..."
psql -d postgres -c "CREATE DATABASE \"$TARGET_DB\";" >/dev/null
CREATED_TARGET=1

echo "Restoring archive into '$TARGET_DB'..."
pg_restore --no-owner --no-privileges --exit-on-error -d "$TARGET_DB" "$DUMP_FILE"

# Disarm trap on successful restore
trap - EXIT

echo "Restoration successfully completed into '$TARGET_DB'."
exit 0
